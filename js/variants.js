// Псевдослучайный генератор с фиксированным зерном (Mulberry32)
function createRng(seed) {
    let s = seed >>> 0;
    return function() {
        s = (s + 0x6D2B79F5) >>> 0;
        let t = Math.imul(s ^ (s >>> 15), 1 | s);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

// Преобразование Бокса-Мюллера для стандартного нормального распределения N(0, 1)
function sampleNormal(rng, mean = 0, std = 1) {
    let u1 = rng();
    let u2 = rng();
    while (u1 === 0) u1 = rng();
    let z0 = Math.sqrt(-2.0 * Math.log(u1)) * Math.cos(2.0 * Math.PI * u2);
    return z0 * std + mean;
}

