function getLabVariantParams(studentId) {
    const seed = 1000 + studentId;
    const info = LAB_VARIANTS_INFO[studentId] || LAB_VARIANTS_INFO[1];
    return {
        studentId: studentId,
        seed: seed,
        nObjects: 500 + 25 * studentId,
        k: 10,
        dims: [2, 4, 8, 16, 32, 64, 128, 256],
        info: info
    };
}

function generateLabData(studentId, d) {
    const params = getLabVariantParams(studentId);
    const rng = createRng(params.seed + d * 17);
    const n = params.nObjects;
    const vNum = studentId;

    let X = [];
    let query = [];

    if (vNum === 1 || vNum === 2) {
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) row.push(sampleNormal(rng, 0, 1));
            X.push(row);
        }
        for (let j = 0; j < d; j++) query.push(sampleNormal(rng, 0, 1));

        if (vNum === 2) {
            for (let j = 0; j < d; j++) {
                let mean = 0;
                for (let i = 0; i < n; i++) mean += X[i][j];
                mean /= n;
                let variance = 0;
                for (let i = 0; i < n; i++) variance += (X[i][j] - mean) ** 2;
                let std = Math.sqrt(variance / n) + 1e-9;
                for (let i = 0; i < n; i++) X[i][j] = (X[i][j] - mean) / std;
                query[j] = (query[j] - mean) / std;
            }
        }
    } else if (vNum === 3 || vNum === 4) {
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) row.push(rng() * 2.0 - 1.0);
            X.push(row);
        }
        for (let j = 0; j < d; j++) query.push(rng() * 2.0 - 1.0);

        if (vNum === 4) {
            for (let i = 0; i < n; i++) {
                let norm = 0;
                for (let j = 0; j < d; j++) norm += X[i][j] ** 2;
                norm = Math.sqrt(norm) + 1e-9;
                for (let j = 0; j < d; j++) X[i][j] /= norm;
            }
            let qNorm = 0;
            for (let j = 0; j < d; j++) qNorm += query[j] ** 2;
            qNorm = Math.sqrt(qNorm) + 1e-9;
            for (let j = 0; j < d; j++) query[j] /= qNorm;
        }
    } else if (vNum === 5 || vNum === 6) {
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) {
                let val = sampleNormal(rng, 0, 1);
                if (j === 0) val *= 1000.0;
                row.push(val);
            }
            X.push(row);
        }
        for (let j = 0; j < d; j++) {
            let val = sampleNormal(rng, 0, 1);
            if (j === 0) val *= 1000.0;
            query.push(val);
        }
        if (vNum === 6) {
            for (let j = 0; j < d; j++) {
                let mean = 0;
                for (let i = 0; i < n; i++) mean += X[i][j];
                mean /= n;
                let variance = 0;
                for (let i = 0; i < n; i++) variance += (X[i][j] - mean) ** 2;
                let std = Math.sqrt(variance / n) + 1e-9;
                for (let i = 0; i < n; i++) X[i][j] = (X[i][j] - mean) / std;
                query[j] = (query[j] - mean) / std;
            }
        }
    } else if (vNum === 7 || vNum === 8) {
        let half = Math.floor(n / 2);
        for (let i = 0; i < n; i++) {
            let shift = i < half ? 0.0 : 3.0;
            let row = [];
            for (let j = 0; j < d; j++) row.push(sampleNormal(rng, shift, 1));
            X.push(row);
        }
        for (let j = 0; j < d; j++) query.push(sampleNormal(rng, 0, 1));
        if (vNum === 8) {
            for (let j = 0; j < d; j++) {
                let mean = 0;
                for (let i = 0; i < n; i++) mean += X[i][j];
                mean /= n;
                for (let i = 0; i < n; i++) X[i][j] -= mean;
                query[j] -= mean;
            }
        }
    } else if (vNum === 9 || vNum === 10) {
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) {
                row.push(rng() < 0.05 ? -Math.log(Math.max(1e-9, rng())) : 0.0);
            }
            X.push(row);
        }
        for (let j = 0; j < d; j++) {
            query.push(rng() < 0.05 ? -Math.log(Math.max(1e-9, rng())) : 0.0);
        }
        if (query.every(v => v === 0)) query[0] = 1.0;
    } else if (vNum === 11 || vNum === 12) {
        for (let i = 0; i < n; i++) {
            let row = [sampleNormal(rng, 0, 1)];
            for (let j = 1; j < d; j++) {
                row.push(0.9 * row[j - 1] + Math.sqrt(1 - 0.81) * sampleNormal(rng, 0, 1));
            }
            X.push(row);
        }
        query = [sampleNormal(rng, 0, 1)];
        for (let j = 1; j < d; j++) {
            query.push(0.9 * query[j - 1] + Math.sqrt(1 - 0.81) * sampleNormal(rng, 0, 1));
        }
        if (vNum === 12) {
            for (let j = 0; j < d; j++) {
                let mean = 0;
                for (let i = 0; i < n; i++) mean += X[i][j];
                mean /= n;
                let variance = 0;
                for (let i = 0; i < n; i++) variance += (X[i][j] - mean) ** 2;
                let std = Math.sqrt(variance / n) + 1e-9;
                for (let i = 0; i < n; i++) X[i][j] = (X[i][j] - mean) / std;
                query[j] = (query[j] - mean) / std;
            }
        }
    } else if (vNum === 13 || vNum === 14) {
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) {
                let u = Math.max(1e-9, rng());
                let val = -Math.log(u);
                if (vNum === 14) val = Math.log(1 + val);
                row.push(val);
            }
            X.push(row);
        }
        for (let j = 0; j < d; j++) {
            let u = Math.max(1e-9, rng());
            let val = -Math.log(u);
            if (vNum === 14) val = Math.log(1 + val);
            query.push(val);
        }
    } else if (vNum === 15 || vNum === 16) {
        // Коши
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) {
                let val = Math.tan(Math.PI * (rng() - 0.5));
                row.push(Math.max(-50, Math.min(50, val)));
            }
            X.push(row);
        }
        for (let j = 0; j < d; j++) {
            let val = Math.tan(Math.PI * (rng() - 0.5));
            query.push(Math.max(-50, Math.min(50, val)));
        }
    } else {
        // По умолчанию
        for (let i = 0; i < n; i++) {
            let row = [];
            for (let j = 0; j < d; j++) row.push(sampleNormal(rng, 0, 1));
            X.push(row);
        }
        for (let j = 0; j < d; j++) query.push(sampleNormal(rng, 0, 1));
    }

    return { X, query };
}


